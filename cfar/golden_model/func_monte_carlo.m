function [Pd_avg, Pfa_avg] = func_monte_carlo(N_trials, num_ref,num_guard,threshold_factor,k,...
                                              pulse,R_tgt, V_tgt,rcs_tgt,Pt,Gt_eff,Gt_max,noise_amp,clutter_amp,...
                                              c,fs,N_PRI,N_Pulse,NFFT,peak_ratio,max_gap)
%FUNC_MONTE_CARLO : Executes the process N_trials times and get Pd,Pf avg
%Can Ertürk
%
%   Purpose:  Monte Carlo function to test the cfar parameters's
%             correctness. It executes the same chain as main_radar_sim
%             (clutter and noise are generated again at each trial, the
%             targets and the antenna gain stay the same) and calculates
%             Pd and Pfa of each trial. Finally returns and displays the
%             average of their value.
%
%             Pd and Pfa are counted with func_score_detections (same as
%             func_performance): only moving targets that the beam
%             illuminates are counted, so it can be used with the 'lla'
%             scenerio.
%
%   inputs:
%             N_trials:           Number of execution trials
%
%             num_ref:            Number of reference cells in cfar
%
%             num_guard:          Number of guard cells
%
%             threshold_factor:   The constant to adjust the treshold
%
%             k:                  A constant to set the treshold's
%                                 reference point to calculate
%
%             pulse:              Transmitted Signal (not windowed)
%
%             R_tgt:              Array that saves exact distances of the
%                                 targets (m)
%
%             V_tgt:              Array that saves exact velocities of the
%                                 targets (m/s)
%
%             rcs_tgt:            Array that saves exact radar cross
%                                 sections of the targets. (m^2)
%
%             Pt:                 Transmiiter Power (W)
%             Gt_eff:             Effective antenna gain of each target (linear)
%             Gt_max:             Antenna gain at the boresight (linear)
%             noise_amp:          Applied noise constant to make more realistic both phase and real
%                                 part of the signal
%             clutter_amp:        The clutter amplification coefficient
%
%             c:                  Constant speed of light in freespace [3e8(m/s)]
%             fs:                 Sampling frequency (samples)
%             N_PRI:              Sample number in one PRI
%             N_Pulse:            Number of transmitted pulse (sample)
%             NFFT:               Number of FFT (for scaling the velocity axis)
%             peak_ratio:         Post-processing peak ratio tolerance
%             max_gap:            Post-processing range gap tolerance (cell)
%
%
%   outputs:
%             Pd_avg:             Average Probability of Detection by
%                                 considering N_trails
%
%             Pfa_avg:            Average Probability of False Alarm
%                                 by considering N_trails

PRF = fs / N_PRI;
lambda = c / 3e9;

% Transmitted pulse is windowed only once and only for the matched filter
% (the received signal is generated by the not windowed pulse like the main code)
pulse_w = func_window_processing(pulse);

Pd_sum = 0;
Pfa_sum = 0;
num_cells = N_PRI;

for trial = 1: N_trials
    clutter = func_clutter_gen(pulse,N_PRI,N_Pulse,clutter_amp,PRF,lambda,c,fs);
    rx = func_get_received_signal(pulse,N_PRI,N_Pulse,R_tgt,V_tgt,rcs_tgt,Pt,Gt_eff,noise_amp);
    rx = rx + clutter;

    mo = func_matched(pulse_w,rx);
    mti_out = func_mti(mo);
    mti_out = func_window_processing(mti_out);
    mti_out = func_fft_processing(mti_out,NFFT);
    [~, os_threshold_map] = func_os_cfar(mti_out,num_ref,num_guard,k,threshold_factor);
    detected_idx = func_cfar_post_processing(mti_out, os_threshold_map,peak_ratio,max_gap);

    % Pd and Pfa of this trial
    [hits,n_valid,false_alarms] = func_score_detections(detected_idx,R_tgt,V_tgt,Gt_eff,Gt_max);

    Pd_sum = Pd_sum + hits/n_valid;
    Pfa_sum = Pfa_sum + false_alarms/num_cells;
end

    Pd_avg = Pd_sum/N_trials;
    fprintf('Average Pd = %.2f\n' , Pd_avg);
    Pfa_avg = Pfa_sum/N_trials;
    fprintf('Average Pfa = %.2e\n', Pfa_avg);
end
